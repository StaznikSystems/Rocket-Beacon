void LowPower_Delay(uint32_t delay_ms)
{
  uint32_t start = HAL_GetTick();
  while ((HAL_GetTick() - start) < delay_ms)
  {
    /* Enter MCU Sleep Mode; SysTick interrupt wakes it every 1 ms */
    HAL_PWR_EnterSLEEPMode(PWR_MAINREGULATOR_ON, PWR_SLEEPENTRY_WFI);
  }
}

/**
 * @brief Flashes status LED a specified number of times on error.
 * @param count Number of times to flash LED.
 */
void BSP_FLashLED(uint8_t count)
{
  for (uint8_t i = 0U; i < count; i++)
  {
    HAL_Delay(500U);
    LED_GPIO_PORT->BSRR = (uint32_t)LED_Pin;
    HAL_Delay(500U);
    LED_GPIO_PORT->BSRR = (uint32_t)LED_Pin << 16U;
  }
}
